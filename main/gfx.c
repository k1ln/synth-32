/*
 * gfx.c — RGB565 framebuffer renderer + LCD init
 * Physical buffer: portrait 720×1280 (HX8394 native).
 * Logical coordinate space: 1280×720 landscape.
 *
 * Coordinate transform (rotation=1, mirror_x=1):
 *   physical (px, py) = (ly, 1279 - lx)
 * Each logical column maps to one contiguous PSRAM run → fast sequential writes.
 */

